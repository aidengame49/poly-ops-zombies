// All 29 non-starter weapons can be won from the Armory Chest (Mystery Box)
export const ARMORY_CHEST_POOL: string[] = WEAPON_LIST.filter((w) => w.id !== 'pistol').map((w) => w.id);

export interface WallBuyDefinition {
  objectType: MapObjectType;
  wepType: string;
  name: string;
  price: number;
  category: NonNullable<WeaponStats['category']>;
  color: string;
}

export const WALL_BUY_ITEMS: WallBuyDefinition[] = WEAPON_LIST.map((w) => ({
  objectType: `wall_buy_${w.id}` as MapObjectType,
  wepType: w.id,
  name: w.name,
  price: w.price,
  category: w.category || 'ar',
  color: w.color,
}));

export const WALL_BUY_CONFIG: Record<string, { name: string; price: number; wepType: string; color: string }> =
  WALL_BUY_ITEMS.reduce(
    (acc, item) => {
      acc[item.objectType] = {
        name: item.name,
        price: item.price,
        wepType: item.wepType,
        color: item.color,
      };
      return acc;
    },
    {} as Record<string, { name: string; price: number; wepType: string; color: string }>
  );
